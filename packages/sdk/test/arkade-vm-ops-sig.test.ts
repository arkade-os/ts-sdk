import { readFileSync } from "node:fs";
import { hex } from "@scure/base";
import { describe, expect, it } from "vitest";
import {
    type Engine,
    ErrUnsupportedByPort,
    ExecutionError,
    type ExtensionCodec,
    executeCovenant,
    KIND,
    MapArkPrevOutFetcher,
    newEngine,
    parseTx,
    ScriptError,
} from "../src/arkade/vm";
import { newTaprootExecutionCtx } from "../src/arkade/vm/engine";
import { computeArkadeSighash } from "../src/arkade/vm/sighash";
import { computeTxSigHashes } from "../src/arkade/vm/tx";
import { vmExtensionCodec } from "../src/extension/vmCodec";

type World = {
    world: string;
    tx: string;
    prevouts: {
        txid: string;
        index: number;
        value: string | null;
        pk: string;
        vtxo: string | null;
    }[];
    mask?: { i: number; s: string } | null;
};

type Case = {
    n: string;
    m: "e" | "c" | "h";
    w: string;
    i?: number;
    s?: string;
    x?: string[];
    l?: string;
    lim?: Record<string, number>;
    exp?: string;
    pkt?: { v: number; s: string; x: string[] }[];
    ht?: number;
    cs?: number;
    st: string[] | null;
    e?: string;
    op?: string;
    pos?: number;
    d?: string;
};

// Generated by test/arkade-vm-oracle (the real pkg/arkade v0.2.0 engine, go1.27.3); "~" marks
// Go's code-less errors by kind.
const oracle: { worlds: World[]; cases: Case[] } = JSON.parse(
    readFileSync(new URL("./fixtures/arkade-vm/ops-sig.json", import.meta.url), "utf8"),
);
const worlds = new Map<string, World>(oracle.worlds.map((w) => [w.world, w]));
const cases = oracle.cases;

function load(name: string) {
    const w = worlds.get(name) as World;
    const tx = parseTx(hex.decode(w.tx));
    const fetcher = new MapArkPrevOutFetcher();
    for (const p of w.prevouts) {
        const op = { txid: hex.decode(p.txid), index: p.index };
        if (p.value !== null) {
            fetcher.setPrevOut(op, { value: BigInt(p.value), script: hex.decode(p.pk) });
        }
        if (p.vtxo !== null) fetcher.setVtxoPkScript(op, hex.decode(p.vtxo));
    }
    // stands in for T5's codec: these scripts read only the masked output (null = Go's fail-open)
    const { mask } = w;
    const codec: ExtensionCodec | undefined =
        mask === undefined
            ? undefined
            : {
                  readExtension: () => null,
                  findEmulatorPacket: () => null,
                  maskExtensionOutput: (t) =>
                      mask && {
                          index: mask.i,
                          output: { value: t.outputs[mask.i].value, script: hex.decode(mask.s) },
                      },
              };
    return { tx, fetcher, codec };
}

function failure(err: unknown): string {
    if (err instanceof ScriptError || err instanceof ExecutionError) {
        return err.code ?? `~${err.kind}`;
    }
    throw err;
}

function covenantEngine(c: Case, w: ReturnType<typeof load>): Engine {
    const { tx, fetcher, codec } = w;
    const inputIndex = c.i ?? 0;
    const vm = newEngine({
        script: hex.decode(c.s ?? "51"),
        tx,
        inputIndex,
        inputAmount: fetcher.fetchPrevOutput(tx.inputs[inputIndex])?.value ?? 0n,
        fetcher,
        sigHashes: computeTxSigHashes(tx, fetcher),
        codec,
    });
    vm.taprootCtx = newTaprootExecutionCtx({ leafVersion: 0xc0, script: hex.decode(c.l ?? "") });
    return vm;
}

function runExpression(c: Case, w: ReturnType<typeof load>) {
    const vm = newEngine({
        script: hex.decode(c.s ?? ""),
        tx: w.tx,
        inputIndex: c.i ?? 0,
        inputAmount: 0n,
        fetcher: w.fetcher,
        expiry: c.exp === undefined ? undefined : BigInt(c.exp),
        emulatorPacket: c.pkt?.map((e) => ({
            vin: e.v,
            script: hex.decode(e.s),
            witness: e.x.map((x) => hex.decode(x)),
        })),
    });
    try {
        for (let done = false; !done; ) done = vm.step();
    } catch (err) {
        return { e: failure(err) };
    }
    return { st: vm.getStack().map((s) => hex.encode(s)) };
}

// the stack is what Go's step callback last saw; the outcome comes from executeCovenant itself
function runCovenant(c: Case, w: ReturnType<typeof load>) {
    const limits = c.lim && new Map(Object.entries(c.lim).map(([op, n]) => [Number(op), n]));
    const witness = (c.x ?? []).map((x) => hex.decode(x));
    const vm = covenantEngine(c, w);
    if (limits) vm.limits = limits;
    vm.setStack(witness);
    let st = vm.getStack();
    try {
        for (let done = false; !done; st = vm.getStack()) done = vm.step();
    } catch {}
    const got = { st: st.map((s) => hex.encode(s)) };
    try {
        executeCovenant({
            script: hex.decode(c.s ?? ""),
            tapLeaf: { leafVersion: 0xc0, script: hex.decode(c.l ?? "") },
            witness,
            tx: w.tx,
            inputIndex: c.i ?? 0,
            fetcher: w.fetcher,
            codec: w.codec,
            limits,
        });
    } catch (err) {
        if (!(err instanceof ExecutionError)) throw err;
        return { ...got, e: failure(err), op: err.opcode, pos: err.position };
    }
    return got;
}

function runDigest(c: Case, w: ReturnType<typeof load>) {
    const vm = covenantEngine({ ...c, s: "51" }, w);
    if (vm.taprootCtx && c.cs !== undefined) vm.taprootCtx.codeSepPos = c.cs;
    try {
        return { d: hex.encode(computeArkadeSighash(vm, c.ht ?? 0)) };
    } catch (err) {
        return { e: failure(err) };
    }
}

const expected = (c: Case) => {
    if (c.m === "e") return c.e ? { e: c.e } : { st: c.st };
    if (c.m === "h") return c.d ? { d: c.d } : { e: `~${KIND.sigHash}` };
    return c.e ? { st: c.st, e: c.e, op: c.op, pos: c.pos } : { st: c.st };
};

const run = { e: runExpression, c: runCovenant, h: runDigest };

describe("T4 opcodes against the Go engine (pkg/arkade v0.2.0)", () => {
    it.each(cases.map((c) => [c.n, c] as const))("%s", (_name, c) => {
        expect(run[c.m](c, load(c.w))).toEqual(expected(c));
    });
});

describe("the extension-output worlds through src/extension's codec", () => {
    const masked = cases.filter((c) => c.m !== "e" && worlds.get(c.w)?.mask !== undefined);
    it.each(masked.map((c) => [c.n, c] as const))("%s", (_name, c) => {
        expect(run[c.m](c, { ...load(c.w), codec: vmExtensionCodec })).toEqual(expected(c));
    });
});

describe("port-only paths, unreachable through Go's exported API", () => {
    const find = (name: string) => cases.find((c) => c.n === name) as Case;
    const signed = () => find("checksig/masked-default");

    const thrown = (fn: () => unknown): unknown => {
        try {
            fn();
        } catch (err) {
            return err;
        }
        throw new Error("expected a throw");
    };

    function run(c: Case, world: string, codec: ExtensionCodec | undefined, script?: string) {
        const vm = covenantEngine({ ...c, s: script ?? c.s }, { ...load(world), codec });
        vm.setStack((c.x ?? []).map((x) => hex.decode(x)));
        for (let done = false; !done; ) done = vm.step();
        return vm;
    }

    const throwing = (err: Error): ExtensionCodec => ({
        readExtension: () => null,
        findEmulatorPacket: () => null,
        maskExtensionOutput: () => {
            throw err;
        },
    });

    it("OP_CHECKTIME compares against the injected clock", () => {
        const at = (script: string, now: bigint) => {
            const w = load("d");
            const vm = newEngine({
                script: hex.decode(script),
                ...w,
                inputIndex: 0,
                inputAmount: 0n,
                now,
            });
            for (let done = false; !done; ) done = vm.step();
            return vm.getStack().map((s) => hex.encode(s));
        };
        expect(at("02e803dc", 1000n)).toEqual(["01"]);
        expect(at("02e903dc", 1000n)).toEqual([""]);
        expect(at("02e903dc", 1001n)).toEqual(["01"]);
    });

    it("a codec that fails to re-encode is an invalid signature, and OP_SIGHASH's error", () => {
        const codec = throwing(new Error("re-encode failed"));
        expect(thrown(() => run(signed(), "mask", codec))).toMatchObject({ code: "ErrNullFail" });
        expect(thrown(() => run(signed(), "mask", codec, "51f6"))).toMatchObject({
            kind: KIND.sigHash,
        });
    });

    it("never swallows ErrUnsupportedByPort, whether the codec throws it or is missing", () => {
        const refusing = throwing(new ErrUnsupportedByPort("not ported"));
        for (const codec of [refusing, undefined]) {
            expect(thrown(() => run(signed(), "mask", codec))).toBeInstanceOf(ErrUnsupportedByPort);
            expect(thrown(() => run(signed(), "mask", codec, "51f6"))).toBeInstanceOf(
                ErrUnsupportedByPort,
            );
        }
    });

    it("masks the outputs once per engine", () => {
        const codec = load("mask").codec as ExtensionCodec;
        let calls = 0;
        const counting: ExtensionCodec = {
            ...codec,
            maskExtensionOutput: (t) => {
                calls++;
                return codec.maskExtensionOutput(t);
            },
        };
        const vm = run(signed(), "mask", counting, "51f651f653f600f6");
        expect([calls, vm.getStack().length]).toEqual([1, 5]);
    });

    it("reads the BIP-341 midstates only when ANYONECANPAY is unset", () => {
        const w = load("d");
        const bare = newEngine({ script: hex.decode("51"), ...w, inputIndex: 0, inputAmount: 0n });
        bare.taprootCtx = newTaprootExecutionCtx({
            leafVersion: 0xc0,
            script: hex.decode(signed().l ?? ""),
        });
        expect(thrown(() => computeArkadeSighash(bare, 0x01))).toMatchObject({ kind: "ErrPanic" });
        const full = covenantEngine(signed(), w);
        expect(computeArkadeSighash(bare, 0x81)).toEqual(computeArkadeSighash(full, 0x81));
    });
});
